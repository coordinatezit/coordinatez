// Build-time generator: samples a lat/lon grid, keeps points that fall on land,
// and writes a compact static array to src/data/land-dots.ts. This keeps d3-geo
// and the world-atlas dataset OUT of the client bundle — the app ships only the
// resulting coordinates, so the hero globe loads instantly with no runtime
// point-in-polygon computation.
import { createRequire } from "module";
import { writeFileSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";

const require = createRequire(import.meta.url);
const { geoContains } = await import("d3-geo");
const { feature } = await import("topojson-client");
const land110m = require("world-atlas/land-110m.json");

const land = feature(land110m, land110m.objects.land);

const dots = [];
for (let lat = -78; lat <= 84; lat += 3) {
  const cos = Math.cos((lat * Math.PI) / 180);
  const step = 3 / Math.max(0.12, cos);
  for (let lon = -180; lon < 180; lon += step) {
    if (geoContains(land, [lon, lat])) {
      dots.push([Math.round(lat * 10) / 10, Math.round(lon * 10) / 10]);
    }
  }
}

const __dirname = dirname(fileURLToPath(import.meta.url));
const out = join(__dirname, "..", "src", "data", "land-dots.ts");
const body = `// AUTO-GENERATED by scripts/generate-land-dots.mjs — do not edit by hand.
// [latitude, longitude] points sampled on land, used to draw the hero globe's
// continents without shipping the world-atlas dataset to the browser.
export const landDots: [number, number][] = ${JSON.stringify(dots)};
`;
writeFileSync(out, body);
console.log(`Wrote ${dots.length} land dots to ${out}`);
